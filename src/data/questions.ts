// Helper to get 10 questions for a quiz session with random sampling
export function getQuizQuestions(category: CategoryId, level?: number, difficulty?: Difficulty): Question[] {
  let pool = QUESTIONS_DB.filter((q) => q.category === category);

  if (level !== undefined && level > 0) {
    const levelMatch = pool.filter((q) => q.level === level);
    if (levelMatch.length >= 5) {
      pool = levelMatch;
    }
  } else if (difficulty) {
    const diffMatch = pool.filter((q) => q.difficulty === difficulty);
    if (diffMatch.length >= 5) {
      pool = diffMatch;
    }
  }

  // Shuffle pool
  const shuffled = [...pool].sort(() => Math.random() - 0.5);

  // Pick up to 10 questions. If pool has fewer than 10, repeat or mix adjacent
  if (shuffled.length >= 10) {
    return shuffled.slice(0, 10);
  }

  // Fallback: fill remaining with other questions from the same category
  const remaining = QUESTIONS_DB.filter(
    (q) => q.category === category && !shuffled.some((s) => s.id === q.id)
  ).sort(() => Math.random() - 0.5);

  const combined = [...shuffled, ...remaining];
  return combined.slice(0, Math.min(10, combined.length));
}
